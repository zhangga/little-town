const test = require('node:test')
const assert = require('node:assert/strict')
const { buildTownGrid, moveTownBuilding, dropCell, layoutPayload } = require('../miniapp/utils/town-layout')
const { harness, tap } = require('./town-life-test.cjs')

test('the complete map is available before construction and valid old placements survive normalization', () => {
  const empty = buildTownGrid([], true)
  assert.equal(empty.plots.length, 18)
  assert.equal(empty.plots.filter(plot => !plot.occupied).length, 17)
  const buildings = [{id: 1, name: '学校', position_x: 60, position_y: 60}, {id: 2, name: '医院', position_x: 2, position_y: 5}]
  const before = JSON.stringify(buildings)
  const grid = buildTownGrid(buildings, true)
  assert.equal(grid.plots.length, empty.plots.length)
  assert.equal(grid.plots[17].id, 2)
  assert.equal(grid.plots[1].id, 1)
  assert.equal(JSON.stringify(buildings), before)
  assert.equal(buildTownGrid(Array.from({length: 11}, (_, index) => ({id: index + 1})), true).plots.length, 18)
  assert.equal(buildTownGrid([], true, {rows: 12}).plots.length, 36)
})

test('moving into a vacant cell and swapping buildings or the home preserves every identity', () => {
  const buildings = [{id: 1, name: '学校'}, {id: 2, name: '医院'}]
  const original = buildTownGrid(buildings, true)
  const moved = moveTownBuilding(original.buildings, original.layout.home, 6, 1, 17)
  assert.equal(moved.plots[17].id, 1)
  assert.equal(moved.plots[1].occupied, false)
  const swapped = moveTownBuilding(moved.buildings, moved.layout.home, 6, 2, 17)
  assert.equal(swapped.plots[17].id, 2)
  assert.equal(swapped.plots[2].id, 1)
  const home = moveTownBuilding(swapped.buildings, swapped.layout.home, 6, 'home', 17)
  assert.equal(home.plots[17].home, true)
  assert.equal(home.plots[0].id, 2)
  assert.deepEqual(home.buildings.map(building => building.id).sort(), [1, 2])
  assert.equal(moveTownBuilding(home.buildings, home.layout.home, 6, 999, 1), null)
  assert.equal(moveTownBuilding(home.buildings, home.layout.home, 6, 1, 18), null)
  assert.deepEqual(Object.keys(layoutPayload(home)).sort(), ['buildings', 'home'])
})

test('drop coordinates account for narrow screens and map scrolling and clamp at map edges', () => {
  const geometry = {left: 0, top: 100, width: 320, scrollTop: 0}
  assert.equal(dropCell({clientX: 270, clientY: 180}, geometry, 0, 6), 2)
  assert.equal(dropCell({clientX: 270, clientY: 180}, geometry, 344 * 320 / 750, 6), 5)
  assert.equal(dropCell({clientX: -100, clientY: -100}, geometry, 0, 6), 0)
  assert.equal(dropCell({clientX: 9999, clientY: 9999}, geometry, 0, 6), 17)
})

