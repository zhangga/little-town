test('failed layout saves retain the draft and a hidden page keeps it until retry or cancel', async () => {
  const h = await harness({put: async () => { throw Error('网络中断') }})
  const before = layoutPayload(h.page.data)
  await h.page.onToggleLayout()
  h.page.placeLayoutBuilding(1, 17)
  await h.page.onToggleLayout()
  assert.deepEqual(h.errors, ['网络中断'])
  assert.equal(h.page.data.editingLayout, true)
  assert.equal(h.page.data.layoutSaving, false)
  assert.equal(h.page.data.plots[17].id, 1)
  const requests = h.calls.length
  h.page.onHide(); h.page.onShow()
  assert.equal(h.calls.length, requests)
  assert.equal(h.page.data.plots[17].id, 1)
  h.page.onCancelLayout()
  assert.equal(h.page.data.editingLayout, false)
  assert.deepEqual(layoutPayload(h.page.data), before)
  assert.equal(h.calls.filter(call => call.method === 'PUT').length, 1)
  await h.page.onToggleLayout()
  h.page.placeLayoutBuilding(1, 17)
  h.api.put = async (_, body) => ({layout: {...body, rows: 6, columns: 3}})
  await h.page.onToggleLayout()
  assert.equal(h.page.data.editingLayout, false)
  assert.equal(h.page.data.plots[17].id, 1)
  h.page.onUnload()
})

test('touch drag snaps to a destination, scrolls at the viewport edge, and cancels without moving', async () => {
  const h = await harness()
  await h.page.onToggleLayout()
  h.page._layoutGeometry = {left: 0, top: 100, width: 375, scrollTop: 0}
  h.page._layoutViewport = {top: 100, bottom: 600, height: 500}
  h.page.onLayoutTouchStart({...tap({index: 1}), touches: [{clientX: 180, clientY: 150}]})
  h.page.onLayoutTouchMove({touches: [{clientX: 185, clientY: 150}]})
  assert.equal(h.page.data.dragging, false)
  h.page.onLayoutTouchMove({touches: [{clientX: 310, clientY: 590}]})
  assert.equal(h.page.data.dragging, true)
  assert.equal(h.page.data.dropSlot, 8)
  h.strollClock.tick(120)
  assert.equal(h.page.data.mapScrollTop, 36)
  assert.equal(h.page.data.dropSlot, 11)
  h.page.onLayoutTouchEnd({changedTouches: [{clientX: 310, clientY: 590}]})
  assert.equal(h.page.data.plots[11].id, 1)
  assert.equal(h.page.data.dragging, false)
  assert.equal(h.strollClock.pending(), 0)
  // A native tap fired after touchend must not open a second selection.
  h.page.onPlotTap(tap({index: 11}))
  assert.equal(h.page.data.moveSelection, '')
  h.page.onLayoutTouchStart({...tap({index: 11}), touches: [{clientX: 310, clientY: 590}]})
  h.page.onLayoutTouchMove({touches: [{clientX: 40, clientY: 120}]})
  h.page.stopLayoutDrag()
  assert.equal(h.page.data.plots[11].id, 1)
  assert.equal(h.strollClock.pending(), 0)
  h.page.onHide()
  assert.equal(h.page.data.dragging, false)
  h.page.onUnload()
})

